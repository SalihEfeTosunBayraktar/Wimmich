async function openViewer(assetId) {
    const overlay = $('viewer-overlay');
    overlay.classList.remove('hidden');
    document.body.style.overflow = 'hidden';

    // Cleared synchronously (before the asset even loads) so the previous
    // photo's similar-badge/strip never flashes onto the new one while the
    // fetch for it is still in flight.
    _viewerSimilarAssets = [];
    _updateSimilarBadge([]);
    _viewerTags = [];

    _clearOcrHighlights();

    try {
        const asset = await API.getAsset(assetId);
        state.viewerAsset = asset;
        renderViewerMedia(asset);
        updateViewerControls(asset);
        // Only while actively browsing OCR-only search results - navigating
        // away from the search (or leaving OCR mode) naturally stops this
        // from firing for the next photo opened, which is what "temporary,
        // clears when the search ends" means here.
        if (asset.file_type === 'IMAGE' && state.gallery.searchMode === 'ocr' && state.gallery.searchQuery) {
            _loadOcrHighlights(assetId, state.gallery.searchQuery);
        }
        // A no-op when the slideshow isn't running (checks _slideshowActive
        // itself) - covers slideshow advances AND manual navigation through
        // this one shared path uniformly, rather than needing every caller
        // to remember to call it.
        _scheduleSlideshowAdvance();
        // The info sidebar (EXIF, people, similar photos...) otherwise kept
        // showing the previous photo's data after navigating via prev/next
        // or a similar-photos click while it was already open.
        const sidebar = $('viewer-sidebar');
        if (sidebar && !sidebar.classList.contains('hidden')) {
            renderViewerInfo(asset);
        }
        _loadSimilarForViewer(assetId);
        _loadTagsForViewer(assetId);
    } catch (e) { toast(e.message, 'error'); closeViewer(); }
}

function renderViewerMedia(asset) {
    const container = $('viewer-media');
    if (asset.file_type === 'VIDEO') {
        container.innerHTML = `<video src="${asset.file_url}" controls autoplay style="max-width:100%;max-height:100%"></video>`;
    } else {
        container.innerHTML = `<img src="${asset.file_url}" alt="${escHtml(asset.file_name)}"><div class="ocr-highlight-layer" id="viewer-ocr-highlight-layer"></div>`;
        const img = container.querySelector('img');
        // The layer is positioned from the img's own rendered box (see
        // _updateOcrHighlightLayerRect) - that box isn't known until the
        // image has actually loaded and laid out, and cached images can
        // fire 'load' before this listener attaches, hence both.
        img.addEventListener('load', _updateOcrHighlightLayerRect);
        if (img.complete) _updateOcrHighlightLayerRect();
    }
    // A new <img> always starts unzoomed/uncentered - carrying over the
    // previous photo's zoom level here would be disorienting (and the
    // pan-clamp math below is sized to THIS image's own dimensions anyway).
    _resetZoom();
}

// ─── OCR search-result highlighting ────────────────────────────────
// Draws temporary boxes over the spot(s) in the currently-open photo that
// matched an OCR-only search query (see gallery.js's searchMode) - purely
// visual, nothing persisted; the boxes just aren't fetched/shown once the
// user leaves OCR search mode or closes the viewer.
let _ocrHighlightBoxes = [];

async function _loadOcrHighlights(assetId, query) {
    try {
        const res = await API.getOcrMatches(assetId, query);
        // The viewer may have already moved to a different photo (or closed)
        // by the time this resolves - only apply it if still relevant.
        if (!state.viewerAsset || state.viewerAsset.id !== assetId) return;
        _ocrHighlightBoxes = res.boxes || [];
        _renderOcrHighlights();
    } catch (e) { /* non-critical - just skip the overlay */ }
}

function _clearOcrHighlights() {
    _ocrHighlightBoxes = [];
}

function _renderOcrHighlights() {
    const layer = $('viewer-ocr-highlight-layer');
    if (!layer) return;
    layer.innerHTML = _ocrHighlightBoxes.map(b => `
        <div class="ocr-highlight-box" style="left:${b.left * 100}%;top:${b.top * 100}%;width:${b.width * 100}%;height:${b.height * 100}%"></div>
    `).join('');
    _updateOcrHighlightLayerRect();
}

// Positions the highlight layer to exactly cover the <img>'s own rendered
// box within .viewer-media - recomputed on every zoom/pan/resize since
// object-fit:contain letterboxing and the img's own CSS transform (see
// _applyZoomTransform) both affect where that box actually is, and
// getBoundingClientRect() already accounts for any transform applied.
function _updateOcrHighlightLayerRect() {
    const layer = $('viewer-ocr-highlight-layer');
    const container = $('viewer-media');
    const img = container && container.querySelector('img');
    if (!layer || !img) return;
    if (!_ocrHighlightBoxes.length) {
        layer.style.display = 'none';
        return;
    }
    const imgRect = img.getBoundingClientRect();
    const containerRect = container.getBoundingClientRect();
    layer.style.display = '';
    layer.style.left = `${imgRect.left - containerRect.left}px`;
    layer.style.top = `${imgRect.top - containerRect.top}px`;
    layer.style.width = `${imgRect.width}px`;
    layer.style.height = `${imgRect.height}px`;
}
window.addEventListener('resize', _updateOcrHighlightLayerRect);

function updateViewerControls(asset) {
    const favBtn = $('viewer-favorite');
    favBtn.classList.toggle('active', asset.is_favorite);
}

async function deleteCurrentViewerAsset() {
    if (!state.viewerAsset) return;
    const deletedId = state.viewerAsset.id;
    await API.trashAsset(deletedId);
    toast(t('viewer.moved_to_trash'), 'success');

    // Drop it from the underlying grid so the page is already correct
    // once the viewer closes, without a full reload.
    const card = document.querySelector(`.photo-card[data-id="${deletedId}"]`);
    if (card) card.remove();

    const deletedIndex = state.viewerList.indexOf(deletedId);
    if (deletedIndex !== -1) state.viewerList.splice(deletedIndex, 1);

    if (!state.viewerList.length) {
        closeViewer();
        return;
    }
    // The next photo shifts into the deleted one's slot, so keeping the
    // same index (bounds-checked for "it was the last one") lands on it.
    state.viewerIndex = deletedIndex === -1 ? 0 : Math.min(deletedIndex, state.viewerList.length - 1);
    openViewer(state.viewerList[state.viewerIndex]);
}

function closeViewer() {
    stopSlideshow();
    if (document.fullscreenElement) document.exitFullscreen().catch(() => {});
    $('viewer-overlay').classList.add('hidden');
    $('viewer-sidebar').classList.add('hidden');
    $('viewer-more-menu').classList.add('hidden');
    document.body.style.overflow = '';
    state.viewerAsset = null;
    _zoomScale = 1;
    _zoomX = 0;
    _zoomY = 0;

    // Hiding the overlay is just CSS (display:none) - it doesn't stop a
    // playing <video>, so its audio kept going in the background after
    // closing. Pausing isn't enough on its own either: some browsers keep
    // buffering/decoding a paused-but-still-loaded video, so the element
    // is removed from the DOM entirely.
    const video = $('viewer-media').querySelector('video');
    if (video) {
        video.pause();
        video.removeAttribute('src');
        video.load();
    }
    $('viewer-media').innerHTML = '';
}

// Pages this can be launched from directly via the topbar button (see
// router.js's navigateTo() and albums.js's openAlbum(), the one place that
// bypasses navigateTo entirely and so has to show/hide this itself).
const SLIDESHOW_PAGES = new Set(['gallery']);
const SLIDESHOW_INTERVAL_MS = 4000;
// How long to wait for a video's own 'ended' event before giving up on it
// and advancing anyway - a safety net for a video that errors or never
// actually starts playing, not a normal-path timeout.
const SLIDESHOW_VIDEO_FALLBACK_MS = 5 * 60 * 1000;
let _slideshowActive = false;
let _slideshowTimer = null;

// Standard Fullscreen API - covers desktop and Android Chrome/Firefox/etc.
// iOS Safari doesn't implement element-level requestFullscreen at all (only
// a video-specific webkitEnterFullscreen()), so this silently no-ops there
// rather than pretending to support it; every other target platform works.
function toggleFullscreen() {
    if (document.fullscreenElement) {
        document.exitFullscreen().catch(() => {});
    } else {
        $('viewer-overlay').requestFullscreen?.().catch(() => {});
    }
}

function _updateFullscreenButton() {
    const btn = $('viewer-fullscreen');
    if (!btn) return;
    const active = !!document.fullscreenElement;
    btn.classList.toggle('active', active);
    btn.title = active ? t('viewer.fullscreen_exit') : t('viewer.fullscreen_enter');
}

function _updateSlideshowButton() {
    const btn = $('viewer-slideshow');
    if (!btn) return;
    btn.classList.toggle('active', _slideshowActive);
    btn.title = _slideshowActive ? t('viewer.slideshow_stop') : t('viewer.slideshow_start');
}

function toggleSlideshow() {
    if (_slideshowActive) stopSlideshow();
    else startSlideshow();
}

function startSlideshow() {
    if (_slideshowActive || !state.viewerList.length) return;
    _slideshowActive = true;
    _updateSlideshowButton();
    _scheduleSlideshowAdvance();
}

function stopSlideshow() {
    if (!_slideshowActive) return;
    _slideshowActive = false;
    if (_slideshowTimer) {
        clearTimeout(_slideshowTimer);
        _slideshowTimer = null;
    }
    _updateSlideshowButton();
}

// Called once each time a new asset finishes loading into the viewer while
// the slideshow is running (see openViewer) - a video waits for its own
// 'ended' event instead of the fixed image interval, so a 20s clip isn't
// cut off after 4s and a 2s clip doesn't leave 2s of dead air before
// advancing. Reproduced directly: the fixed interval was firing mid-
// playback regardless of the video's actual length.
function _scheduleSlideshowAdvance() {
    if (_slideshowTimer) {
        clearTimeout(_slideshowTimer);
        _slideshowTimer = null;
    }
    if (!_slideshowActive) return;

    const asset = state.viewerAsset;
    const video = asset?.file_type === 'VIDEO' ? $('viewer-media').querySelector('video') : null;
    if (video) {
        video.addEventListener('ended', _slideshowAdvance, { once: true });
        _slideshowTimer = setTimeout(_slideshowAdvance, SLIDESHOW_VIDEO_FALLBACK_MS);
        return;
    }
    _slideshowTimer = setTimeout(_slideshowAdvance, SLIDESHOW_INTERVAL_MS);
}

async function _slideshowAdvance() {
    // Guards a video's 'ended' listener firing after the slideshow was
    // already stopped (e.g. the user paused it but let the video keep
    // playing) - {once: true} still lets it fire once more harmlessly
    // without this check.
    if (!_slideshowActive) return;
    if (_slideshowTimer) {
        clearTimeout(_slideshowTimer);
        _slideshowTimer = null;
    }

    // Reached the end of what's loaded: the main gallery still has more on
    // the server (navigateViewer already knows how to fetch the next page
    // for that exact case), everywhere else just loops back to the start -
    // a slideshow that quietly stopped advancing after one pass through the
    // album would look broken, not "done".
    const atEnd = state.viewerIndex + 1 >= state.viewerList.length;
    const galleryHasMore = state.currentPage === 'gallery' && state.gallery.totalPages > state.gallery.page;
    if (atEnd && !galleryHasMore) {
        state.viewerIndex = -1; // navigateViewer(1) below lands on 0
    }
    await navigateViewer(1);
}

// Entry point for the topbar "▶️ Slideshow" button - builds the list from
// whatever's actually rendered on the current page rather than trusting
// state.viewerList to already be populated (right after a fresh page load,
// before any card has been clicked, some pages haven't set it yet).
function startSlideshowFromCurrentPage() {
    const cards = Array.from(document.querySelectorAll('#page-content .photo-card'));
    if (!cards.length) {
        toast(t('viewer.slideshow_no_photos'), 'info');
        return;
    }
    state.viewerList = cards.map(c => c.dataset.id);
    state.viewerIndex = 0;
    openViewer(state.viewerList[0]);
    startSlideshow();
}

function initViewer() {
    $('slideshow-btn').onclick = startSlideshowFromCurrentPage;
    $('viewer-fullscreen').onclick = toggleFullscreen;
    // Keeps the icon/title in sync when fullscreen is exited some way other
    // than this button - Esc key, the browser/OS's own fullscreen exit UI.
    document.addEventListener('fullscreenchange', _updateFullscreenButton);
    $('viewer-close').onclick = closeViewer;
    // Manual navigation pauses an active slideshow - jumping in "wait, go
    // back" and having it just keep auto-advancing anyway would be
    // surprising. _slideshowAdvance() calls navigateViewer() directly
    // itself, bypassing these wrappers, so its own tick never stops itself.
    $('viewer-prev').onclick = () => { stopSlideshow(); navigateViewer(-1); };
    $('viewer-next').onclick = () => { stopSlideshow(); navigateViewer(1); };
    $('viewer-slideshow').onclick = toggleSlideshow;
    $('viewer-favorite').onclick = async () => {
        if (!state.viewerAsset) return;
        const r = await API.toggleFavorite(state.viewerAsset.id);
        state.viewerAsset.is_favorite = r.is_favorite;
        updateViewerControls(state.viewerAsset);
        toast(r.is_favorite ? t('viewer.added_to_favorites') : t('viewer.removed_from_favorites'), 'success');
    };
    $('viewer-download').onclick = () => {
        if (!state.viewerAsset) return;
        const a = document.createElement('a');
        a.href = state.viewerAsset.file_url;
        a.download = state.viewerAsset.file_name;
        a.click();
    };
    $('viewer-archive').onclick = async () => {
        if (!state.viewerAsset) return;
        const r = await API.toggleArchive(state.viewerAsset.id);
        toast(r.is_archived ? t('viewer.archived') : t('viewer.unarchived'), 'success');
        closeViewer();
        navigateTo(state.currentPage);
    };
    $('viewer-delete').onclick = deleteCurrentViewerAsset;
    $('viewer-similar-badge').onclick = _openSimilarFromBadge;
    $('viewer-info').onclick = () => {
        const sidebar = $('viewer-sidebar');
        sidebar.classList.toggle('hidden');
        if (!sidebar.classList.contains('hidden') && state.viewerAsset) {
            renderViewerInfo(state.viewerAsset);
        }
    };
    $('viewer-sidebar-close').onclick = () => $('viewer-sidebar').classList.add('hidden');

    // Less-frequently-used actions (slideshow/fullscreen/info/archive) live
    // behind this "more" button instead of the main bar - on a narrow phone
    // screen, all 10 buttons the toolbar used to have never fit, and the
    // trailing ones (including Close) silently ran off the edge of the
    // screen with no way to reach them. Their own onclick handlers above
    // are untouched; this only closes the popup afterward.
    $('viewer-more').onclick = (e) => {
        e.stopPropagation();
        $('viewer-more-menu').classList.toggle('hidden');
    };
    $('viewer-more-menu').addEventListener('click', (e) => {
        if (e.target.closest('button')) $('viewer-more-menu').classList.add('hidden');
    });
    document.addEventListener('click', (e) => {
        const menu = $('viewer-more-menu');
        if (!menu.classList.contains('hidden') && !e.target.closest('.viewer-more-wrap')) {
            menu.classList.add('hidden');
        }
    });

    document.addEventListener('keydown', (e) => {
        if ($('viewer-overlay').classList.contains('hidden')) return;
        if (e.key === 'Escape') closeViewer();
        if (e.key === 'ArrowLeft') { stopSlideshow(); navigateViewer(-1); }
        if (e.key === 'ArrowRight') { stopSlideshow(); navigateViewer(1); }
        if (e.key === 'Delete') deleteCurrentViewerAsset();
        if (e.key === ' ') { e.preventDefault(); toggleSlideshow(); }
    });

    _initViewerSwipe();
    _initViewerZoom();
}

function _initViewerSwipe() {
    const media = $('viewer-media');
    let startX = 0, startY = 0, touching = false;

    media.addEventListener('touchstart', (e) => {
        // A pinch (2+ touches), or any single-finger touch once already
        // zoomed in, belongs to _initViewerZoom()'s pan handling instead -
        // swiping to the next/prev photo only makes sense at 1x, where a
        // horizontal drag can't mean "pan around the zoomed-in image".
        if (e.touches.length !== 1 || _zoomScale > 1) { touching = false; return; }
        touching = true;
        startX = e.touches[0].clientX;
        startY = e.touches[0].clientY;
    }, { passive: true });

    media.addEventListener('touchend', (e) => {
        if (!touching) return;
        touching = false;
        const dx = e.changedTouches[0].clientX - startX;
        const dy = e.changedTouches[0].clientY - startY;
        const SWIPE_THRESHOLD = 50;
        if (Math.abs(dx) > SWIPE_THRESHOLD && Math.abs(dx) > Math.abs(dy) * 1.5) {
            stopSlideshow();
            navigateViewer(dx < 0 ? 1 : -1);
        }
    }, { passive: true });
}

// Zoom/pan for the current photo - ctrl+wheel (also what a trackpad pinch
// fires as, in every browser tested) on desktop, pinch/drag on touch,
// double-click/double-tap to toggle between 1x and 2x. Video isn't covered
// (its own <video controls> already owns touch/wheel for scrubbing/volume
// - layering zoom gestures on top would fight it), so every handler here
// bails out when the current media isn't an <img>.
let _zoomScale = 1;
let _zoomX = 0;
let _zoomY = 0;
const ZOOM_MIN = 1;
const ZOOM_MAX = 5;
const ZOOM_DOUBLE_TAP = 2;

function _currentViewerImg() {
    return $('viewer-media').querySelector('img');
}

function _clampZoomPan() {
    const img = _currentViewerImg();
    if (!img) return;
    const container = $('viewer-media');
    // offsetWidth/Height is the image's own laid-out (untransformed) size -
    // transform:scale doesn't affect layout, so this stays reliable at any
    // zoom level instead of needing the container's size guessed at.
    const scaledW = img.offsetWidth * _zoomScale;
    const scaledH = img.offsetHeight * _zoomScale;
    const maxX = Math.max(0, (scaledW - container.clientWidth) / 2);
    const maxY = Math.max(0, (scaledH - container.clientHeight) / 2);
    _zoomX = Math.min(maxX, Math.max(-maxX, _zoomX));
    _zoomY = Math.min(maxY, Math.max(-maxY, _zoomY));
}

function _applyZoomTransform(smooth) {
    const img = _currentViewerImg();
    if (!img) return;
    img.style.transition = smooth ? 'transform 150ms ease' : 'none';
    img.style.transform = `translate(${_zoomX}px, ${_zoomY}px) scale(${_zoomScale})`;
    img.classList.toggle('zoomed', _zoomScale > 1);
    _updateOcrHighlightLayerRect();
}

function _resetZoom() {
    _zoomScale = 1;
    _zoomX = 0;
    _zoomY = 0;
    _applyZoomTransform(false);
}

function _setZoom(scale, smooth) {
    _zoomScale = Math.min(ZOOM_MAX, Math.max(ZOOM_MIN, scale));
    if (_zoomScale === ZOOM_MIN) {
        _zoomX = 0;
        _zoomY = 0;
    } else {
        _clampZoomPan();
    }
    _applyZoomTransform(smooth);
}

function _initViewerZoom() {
    const media = $('viewer-media');

    // Ctrl+wheel (desktop) - Chrome/Firefox/Safari all report a trackpad
    // pinch gesture as a wheel event with ctrlKey set, so this covers both
    // an actual Ctrl+scroll and a trackpad pinch with the same code path.
    media.addEventListener('wheel', (e) => {
        if (!e.ctrlKey || !_currentViewerImg()) return;
        e.preventDefault();
        _setZoom(_zoomScale - e.deltaY * 0.01, false);
    }, { passive: false });

    media.addEventListener('dblclick', () => {
        if (!_currentViewerImg()) return;
        _setZoom(_zoomScale > 1 ? ZOOM_MIN : ZOOM_DOUBLE_TAP, true);
    });

    // Mouse drag-to-pan once zoomed in - only actually starts panning past
    // a couple pixels of movement, so a plain click still reaches other
    // click handlers (favorite toggle isn't on the image, but nothing else
    // should be eaten by an accidental 1px jitter either).
    let mouseDragging = false, mouseStartX = 0, mouseStartY = 0, panStartX = 0, panStartY = 0;
    media.addEventListener('mousedown', (e) => {
        if (_zoomScale <= 1 || !_currentViewerImg()) return;
        mouseDragging = true;
        mouseStartX = e.clientX;
        mouseStartY = e.clientY;
        panStartX = _zoomX;
        panStartY = _zoomY;
        e.preventDefault();
    });
    window.addEventListener('mousemove', (e) => {
        if (!mouseDragging) return;
        _zoomX = panStartX + (e.clientX - mouseStartX);
        _zoomY = panStartY + (e.clientY - mouseStartY);
        _clampZoomPan();
        _applyZoomTransform(false);
    });
    window.addEventListener('mouseup', () => { mouseDragging = false; });

    // Touch: one finger pans once zoomed in (see _initViewerSwipe's own
    // touchstart, which defers to this instead of treating it as a swipe
    // whenever _zoomScale > 1); two fingers pinch-zoom regardless of
    // current zoom level.
    let pinching = false, pinchStartDist = 0, pinchStartScale = 1;
    let panning = false, touchStartX = 0, touchStartY = 0, touchPanStartX = 0, touchPanStartY = 0;
    let gestureMoved = false;
    let lastTapAt = 0;

    const touchDist = (touches) => Math.hypot(
        touches[0].clientX - touches[1].clientX,
        touches[0].clientY - touches[1].clientY,
    );

    media.addEventListener('touchstart', (e) => {
        if (!_currentViewerImg()) return;
        if (e.touches.length === 2) {
            pinching = true;
            panning = false;
            gestureMoved = true;
            pinchStartDist = touchDist(e.touches);
            pinchStartScale = _zoomScale;
        } else if (e.touches.length === 1 && _zoomScale > 1) {
            panning = true;
            gestureMoved = false;
            touchStartX = e.touches[0].clientX;
            touchStartY = e.touches[0].clientY;
            touchPanStartX = _zoomX;
            touchPanStartY = _zoomY;
        } else {
            gestureMoved = false;
        }
    }, { passive: true });

    media.addEventListener('touchmove', (e) => {
        if (pinching && e.touches.length === 2) {
            e.preventDefault();
            const ratio = touchDist(e.touches) / pinchStartDist;
            _setZoom(pinchStartScale * ratio, false);
        } else if (panning && e.touches.length === 1) {
            e.preventDefault();
            gestureMoved = true;
            _zoomX = touchPanStartX + (e.touches[0].clientX - touchStartX);
            _zoomY = touchPanStartY + (e.touches[0].clientY - touchStartY);
            _clampZoomPan();
            _applyZoomTransform(false);
        }
    }, { passive: false });

    media.addEventListener('touchend', (e) => {
        if (e.touches.length === 0) {
            const wasRealGesture = gestureMoved;
            pinching = false;
            panning = false;
            pinchStartDist = 0;
            // Double-tap to toggle zoom - only for a real stationary tap,
            // not the release at the end of an actual pinch/pan (both also
            // fire touchend at 0 remaining touches).
            if (e.changedTouches.length === 1 && !wasRealGesture) {
                const now = Date.now();
                if (now - lastTapAt < 300) {
                    _setZoom(_zoomScale > 1 ? ZOOM_MIN : ZOOM_DOUBLE_TAP, true);
                    lastTapAt = 0;
                } else {
                    lastTapAt = now;
                }
            }
        }
    }, { passive: true });
}

async function navigateViewer(dir) {
    // Clamp instead of wrapping around - viewerList is often only whatever
    // the current page has loaded so far (the main gallery loads in pages
    // of 60 via infinite scroll), not the whole library, so wrapping past
    // the last loaded item jumped back to the first one instead of doing
    // nothing, which looked like it had looped partway through the library.
    let next = state.viewerIndex + dir;

    // Moving forward past everything the gallery has loaded so far, but
    // there's more on the server - fetch the next page instead of just
    // stopping there, so paging through photos doesn't force closing the
    // viewer, scrolling the grid to trigger a load, and reopening it.
    // Only the main gallery paginates viewerList this way; every other
    // page (albums/people/favorites/etc.) already loads its full list
    // up front, so state.gallery.totalPages > state.gallery.page is only
    // ever true there.
    if (dir > 0 && next >= state.viewerList.length &&
        state.currentPage === 'gallery' && state.gallery.totalPages > state.gallery.page) {
        state.gallery.page++;
        state.gallery.loading = false;
        await loadGalleryPage();
        next = state.viewerIndex + dir;
    }

    if (next < 0 || next >= state.viewerList.length) return;
    state.viewerIndex = next;
    openViewer(state.viewerList[state.viewerIndex]);
}

async function _runViewerReprocess(btn, apiCall, idleLabel, busyLabel) {
    // Only the label span updates - the icon before it is a permanent part
    // of the button, not part of the busy/idle text swap.
    const label = btn.querySelector('.viewer-reprocess-label');
    btn.disabled = true;
    label.textContent = busyLabel;
    try {
        const result = await apiCall();
        toast(result.message, 'success');
    } catch (e) {
        toast(e.message, 'error');
    } finally {
        btn.disabled = false;
        label.textContent = idleLabel;
    }
}

